#!/usr/bin/env node

/**
 * Prebuild script for SEO-044: generates lastmod dates for static sitemap pages
 * from git commit history. Runs as part of prebuild:ssr.
 *
 * Each static page is mapped to its Angular component directory.
 * The most recent git commit date for that directory becomes the lastmod.
 */

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const STATIC_PAGES = [
  { route: '/',                     dir: 'src/app/home' },
  { route: '/about',                dir: 'src/app/home/about' },
  { route: '/about/partner',        dir: 'src/app/home/about-partner' },
  { route: '/about/editorial-standards', dir: 'src/app/home/editorial-standards' },
  { route: '/plans',                dir: 'src/app/home/about-practitioner' },
  { route: '/plans/product',        dir: 'src/app/home/about-company' },
  { route: '/companies',            dir: 'src/app/home/listing-company' },
  { route: '/ambassador-program',   dir: 'src/app/home/landing-ambassador' },
  { route: '/press-release',        dir: 'src/app/home/press-release' },
  { route: '/online-academy',       dir: 'src/app/home/online-academy' },
  { route: '/testimonial',          dir: 'src/app/home/testimonial' },
  { route: '/faq',                  dir: 'src/app/home/faq' },
  { route: '/subscribe/newsletter', dir: 'src/app/home/landing-clubhouse' },
  { route: '/contact-us',           dir: 'src/app/home/contact-us' },
  { route: '/policy',               dir: 'src/app/home/privacy-policy' },
  { route: '/terms',                dir: 'src/app/home/terms-conditions' },
];

function getLastCommitDate(dir) {
  try {
    const result = execSync(
      `git log -1 --format="%ci" -- "${dir}"`,
      { encoding: 'utf-8', stdio: ['pipe', 'pipe', 'pipe'] }
    ).trim();
    if (result) {
      return new Date(result).toISOString().split('T')[0];
    }
  } catch (e) {
    // git not available or no commits for this dir
  }
  return null;
}

const fallback = new Date().toISOString().split('T')[0];
const entries = STATIC_PAGES.map(page => {
  const date = getLastCommitDate(page.dir) || fallback;
  return `  '${page.route}': '${date}',`;
});

const output = `// Auto-generated by scripts/generate-static-page-dates.js — do not edit manually
export const staticPageDates: { [route: string]: string } = {
${entries.join('\n')}
};
`;

const outPath = path.join(__dirname, '..', 'src', 'app', 'static-page-dates.ts');
fs.writeFileSync(outPath, output, 'utf-8');
console.log(`[SEO-044] Generated static-page-dates.ts with ${STATIC_PAGES.length} entries`);
